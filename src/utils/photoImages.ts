/**
 * Returns a high quality photograph URL for a numbered callout node or hotspot pin
 */
export function getNodePictureUrl(nodeId: number | string, nodeTitle?: string): string {
  const numericId = typeof nodeId === 'number' ? nodeId : parseInt(String(nodeId).replace(/\D/g, ''), 10) || 1;
  if (NODE_COMPONENT_PHOTOS[numericId]) {
    return NODE_COMPONENT_PHOTOS[numericId];
  }

  // Fallback hash over title or id
  const str = nodeTitle || String(nodeId);
  let hash = 0;
  for (let i = 0; i < str.length; i++) {
    hash = (hash << 5) - hash + str.charCodeAt(i);
    hash |= 0;
  }
  const keys = Object.keys(NODE_COMPONENT_PHOTOS);
  const selectedKey = Number(keys[Math.abs(hash) % keys.length]);
  return NODE_COMPONENT_PHOTOS[selectedKey] || NODE_COMPONENT_PHOTOS[1];
}



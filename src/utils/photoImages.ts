/**
 * Returns a high-definition real photograph URL matching a blueprint ID or Category
 */
export function getRealPhotographUrl(id: string, category: BlueprintCategory, seedNum: number = 0): string {
  const photos = CATEGORY_REAL_PHOTOS[category] || CATEGORY_REAL_PHOTOS['Mechanical & Engines'];
  let index = 0;

  // Derive deterministic hash from id
  if (id) {
    let hash = 0;
    for (let i = 0; i < id.length; i++) {
      hash = (hash << 5) - hash + id.charCodeAt(i);
      hash |= 0;
    }
    index = Math.abs(hash) % photos.length;
  } else {
    index = Math.abs(seedNum) % photos.length;
  }

  return photos[index];
}

